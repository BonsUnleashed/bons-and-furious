package bons.furious.patch.mcreator_item_animation;

import bons.furious.guard.Fingerprint;
import java.util.LinkedHashMap;
import java.util.Map;
import java.util.Set;
import java.util.concurrent.ConcurrentHashMap;
import org.objectweb.asm.tree.ClassNode;
import org.objectweb.asm.tree.MethodNode;
import org.spongepowered.asm.service.MixinService;

/**
 * mcreator_item_animation_idle (since 1.0.45): one guard per target mod, the design of the mcreator_entity_guards group.
 * Guards decides a switch all or nothing, which would turn this four-mod switch off whenever one of the mods is absent or
 * updated; so the switch's own guard list holds only the Minecraft methods every handler relies on, and each mixin is
 * also checked here before Mixin prepares it (ItemAnimationPlugin.shouldApplyMixin): its target's animatedItems must match
 * the fingerprint of the tested build. A missing mod is skipped silently; a changed build steps aside alone (one WARN).
 *
 * The table is generated from patches/mcreator_item_animation.json "target_guard" (sha256 by
 * tools/mixedproof/lane_m_target_fill.py, which runs the build's GuardTool fill over those entries) - keep the two equal.
 */
public final class TargetGuards {
    /** One target: our mixin, the mod id that ships the class, the class (internal name), the method and its fingerprint. */
    public record Target(String mixin, String modId, String owner, String method, String desc, String sha256) {}

    static final String DESC = "(Lnet/minecraftforge/event/TickEvent$PlayerTickEvent;)V";
    static final String PKG = "bons.furious.mixin.mcreator_item_animation.";
    public static final Map<String, Target> BY_MIXIN = new LinkedHashMap<>();
    private static final Set<String> LOGGED = ConcurrentHashMap.newKeySet();

    static {
        // BEGIN TARGETS (generated by tools/mixedproof/lane_m_target_fill.py from patches/mcreator_item_animation.json)
        add("BornInChaosItemAnimationMixin", "born_in_chaos_v1", "net/mcreator/borninchaosv/init/ItemAnimationFactory", "344821bb96ff52a5f9d39013962afdf79e293fd5606a4fd74db54a1fab189cc8");
        add("RusticEngineerItemAnimationMixin", "rustic_engineer", "net/mcreator/rusticengineer/init/ItemAnimationFactory", "f6363ca7c8403e078eed1bcc6b969f8b65dd098e275a71733a4967cff16b524a");
        add("TerramityItemAnimationMixin", "terramity", "net/mcreator/terramity/init/ItemAnimationFactory", "00676287bf5b9686e1c76caae3936eea81b5428ca97bd2f009d5296817fcc27f");
        add("UnderTheMoonItemAnimationMixin", "under_the_moon", "net/mcreator/underthemoon/init/ItemAnimationFactory", "b6aa5c7918298db7f21d8c52384754182ac8216b21064c4865ca133f989d5b1d");
        // END TARGETS
    }

    private TargetGuards() {
    }

    private static void add(String mixin, String modId, String owner, String sha256) {
        BY_MIXIN.put(PKG + mixin, new Target(PKG + mixin, modId, owner, "animatedItems", DESC, sha256));
    }

    /** IMixinConfigPlugin.shouldApplyMixin, after the switch's own decision: true when this target is the tested build. */
    public static boolean tested(String mixin, String targetClass) {
        Target t = BY_MIXIN.get(mixin);
        String target = targetClass.replace('/', '.');
        if (t == null) {
            if (LOGGED.add("unknown|" + mixin))
                ItemAnimationIdle.LOGGER.warn("Bons and Furious: {}: {} has no recorded target; {} is left unchanged", ItemAnimationIdle.KEY, mixin, target);
            return false;
        }
        if (!t.owner().equals(targetClass.replace('.', '/'))) return false;
        Boolean listed = modListed(t.modId());
        if (Boolean.FALSE.equals(listed)) return false;                       // the mod is not installed
        String why = check(t);
        if (why == null) return true;
        if (why.isEmpty()) {
            if (!Boolean.TRUE.equals(listed)) return false;                   // not installed (early mod list unknown)
            why = target + " not found";
        }
        if (LOGGED.add(mixin))
            ItemAnimationIdle.LOGGER.warn("Bons and Furious: {} skipped for {} because the installed class does not match the supported version ({}); "
                    + "the class is left unchanged, the other mods' handlers keep the switch", ItemAnimationIdle.KEY, target, why);
        return false;
    }

    /** null = the tested build; "" = the class is not there (mod not installed); otherwise what differs. */
    static String check(Target t) {
        ClassNode node = read(t.owner());
        if (node == null) return "";
        for (MethodNode m : node.methods) {
            if (m.name.equals(t.method()) && m.desc.equals(t.desc())) {
                String fp = Fingerprint.of(m);
                return fp.equals(t.sha256()) ? null : t.method() + " differs";
            }
        }
        return t.method() + " missing";
    }

    /** Whether FML's early mod list lists the mod; null when that list is not available (offline tools). */
    private static Boolean modListed(String modId) {
        try {
            var mods = net.minecraftforge.fml.loading.LoadingModList.get();
            return mods == null ? null : mods.getModFileById(modId) != null;
        } catch (Throwable t) {
            return null;
        }
    }

    private static ClassNode read(String internalName) {
        try {
            return MixinService.getService().getBytecodeProvider().getClassNode(internalName.replace('/', '.'));
        } catch (ClassNotFoundException e) {
            return null;
        } catch (Throwable t) {
            ItemAnimationIdle.LOGGER.debug("Bons and Furious: {} could not read {}: {}", ItemAnimationIdle.KEY, internalName, t.toString());
            return null;
        }
    }
}
