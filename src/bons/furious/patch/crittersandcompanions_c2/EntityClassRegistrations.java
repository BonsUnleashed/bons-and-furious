package bons.furious.patch.crittersandcompanions_c2;

import com.google.gson.JsonArray;
import com.google.gson.JsonElement;
import com.google.gson.JsonObject;
import com.google.gson.JsonParser;
import java.io.BufferedReader;
import java.io.IOException;
import java.io.InputStream;
import java.io.InputStreamReader;
import java.nio.charset.StandardCharsets;
import java.nio.file.DirectoryStream;
import java.nio.file.Files;
import java.nio.file.Path;
import java.nio.file.Paths;
import java.util.ArrayList;
import java.util.LinkedHashMap;
import java.util.List;
import java.util.Map;
import java.util.TreeMap;
import java.util.jar.Manifest;
import org.apache.logging.log4j.LogManager;
import org.apache.logging.log4j.Logger;

/**
 * Bons and Furious switch vanilla_entity_class_count_layer, since 1.0.49: the tracked classes OTHER groups register, read once when {@link EntityClassCounts} initialises (the first entity section
 * storage of the game, i.e. the first level). No Mojang or target-mod code here.
 *
 * A group registers by shipping a resource next to its mixin config, named after it:
 *
 *   resources/bons_and_furious.&lt;group&gt;.entity_classes.json
 *   {"layer": "vanilla_entity_class_count_layer",
 *    "entries": [{"class": "com.example.mod.SomeEntity", "key": "example_scan_presence_gate", "mod": "examplemod",
 *                 "why": "free text"}]}
 *
 *   class  the exact binary name of an entity class or an interface (subclasses / implementors are counted with it)
 *   key    optional: counted only while that switch is enabled in bons_and_furious.properties (and not -D disabled)
 *   mod    optional: counted only when a mod with that id is loaded (FML's loading mod list; offline: always)
 *   why    ignored by the layer
 *
 * Where the files are found: the groups are the mixin configs named in our jar's manifest (MixinConfigs, generated by the
 * build from every resources/*.mixins.json); if the manifest lists none of ours, the mixin lines of our guard table
 * (bons_and_furious.guards.tsv, also generated by the build). Offline harnesses pass
 * -Dbons_and_furious.entityClassCountLayer.registrations=dir[;dir...] instead: every bons_and_furious.*.entity_classes.json
 * in those folders (a test JVM has neither the manifest nor the guard table).
 *
 * Order (the indices): the layer's built-in entries first, unchanged (0..11 as in 1.0.48), then the registered names in
 * group-name order and, inside a file, in file order; a name registered twice (or already built in) keeps its first index.
 * Indices live only in this JVM (never saved or sent), so two JVMs with different switches may number differently.
 * A file that cannot be read or parsed, and an entry without a class name, are skipped with a WARN; nothing else is
 * affected.
 */
final class EntityClassRegistrations {
    static final String PROPERTY = "bons_and_furious.entityClassCountLayer.registrations";
    static final String PREFIX = "bons_and_furious.", MIXINS = ".mixins.json", SUFFIX = ".entity_classes.json";
    private static final Logger LOGGER = LogManager.getLogger("Bons and Furious");

    /** The result: every name in index order, and per name the group that registered it ("" = built in). */
    record Table(String[] names, String[] groups, int files, int skipped, String source) {}

    private EntityClassRegistrations() {
    }

    static Table load(String[] builtIn) {
        Map<String, String> byName = new LinkedHashMap<>();   // name -> registering group, in index order
        for (String n : builtIn) byName.putIfAbsent(n, "");
        int files = 0, skipped = 0;
        String source;
        TreeMap<String, String> texts = new TreeMap<>();      // group -> file text, in group-name order
        try {
            String dirs = System.getProperty(PROPERTY);
            if (dirs != null && !dirs.isBlank()) {
                source = "folders " + dirs;
                for (String d : dirs.split("[;" + java.io.File.pathSeparator + "]")) {
                    if (d.isBlank()) continue;
                    Path dir = Paths.get(d.trim());
                    if (!Files.isDirectory(dir)) continue;
                    try (DirectoryStream<Path> s = Files.newDirectoryStream(dir, PREFIX + "*" + SUFFIX)) {
                        for (Path p : s) {
                            String f = p.getFileName().toString();
                            texts.putIfAbsent(f.substring(PREFIX.length(), f.length() - SUFFIX.length()), Files.readString(p, StandardCharsets.UTF_8));
                        }
                    }
                }
            } else {
                List<String> groups = manifestGroups();
                source = "the jar's mixin configs";
                if (groups.isEmpty()) {
                    groups = guardTableGroups();
                    source = "the guard table";
                }
                for (String g : groups) {
                    String text = resource("/" + PREFIX + g + SUFFIX);
                    if (text != null) texts.put(g, text);
                }
            }
        } catch (Throwable t) {
            source = "nothing (" + t + ")";
            LOGGER.warn("Bons and Furious: vanilla_entity_class_count_layer could not list the registered entity classes ({}); it counts its built-in entries only", t.toString());
            texts.clear();
        }
        for (Map.Entry<String, String> file : texts.entrySet()) {
            files++;
            try {
                JsonObject root = JsonParser.parseString(file.getValue()).getAsJsonObject();
                JsonArray entries = root.getAsJsonArray("entries");
                if (entries == null) throw new IllegalArgumentException("no \"entries\" array");
                for (JsonElement e : entries) {
                    JsonObject o = e.getAsJsonObject();
                    String name = o.has("class") ? o.get("class").getAsString().trim() : "";
                    if (name.isEmpty()) {
                        skipped++;
                        LOGGER.warn("Bons and Furious: vanilla_entity_class_count_layer: an entry of {}{}{} has no class name; it is skipped", PREFIX, file.getKey(), SUFFIX);
                        continue;
                    }
                    String key = o.has("key") ? o.get("key").getAsString().trim() : "";
                    String mod = o.has("mod") ? o.get("mod").getAsString().trim() : "";
                    if (!key.isEmpty() && !keyEnabled(key)) continue;
                    if (!mod.isEmpty() && !modLoaded(mod)) continue;
                    byName.putIfAbsent(name, file.getKey());
                }
            } catch (Throwable t) {
                skipped++;
                LOGGER.warn("Bons and Furious: vanilla_entity_class_count_layer could not read {}{}{} ({}); its classes are not counted", PREFIX, file.getKey(), SUFFIX, t.toString());
            }
        }
        String[] names = byName.keySet().toArray(new String[0]);
        String[] groups = byName.values().toArray(new String[0]);
        return new Table(names, groups, files, skipped, source);
    }

    /** The switch named by an entry: enabled in the config (offline, when the config cannot be read: enabled). */
    private static boolean keyEnabled(String key) {
        try {
            return bons.pure.config.PureConfig.isEnabled(key);
        } catch (Throwable t) {
            return true;
        }
    }

    /** FML's loading mod list knows a mod with this id (offline, without that list: true). */
    private static boolean modLoaded(String mod) {
        try {
            net.minecraftforge.fml.loading.LoadingModList list = net.minecraftforge.fml.loading.LoadingModList.get();
            return list == null || list.getModFileById(mod) != null;
        } catch (Throwable t) {
            return true;
        }
    }

    /** The groups of our mixin configs from our jar's manifest (bons_and_furious.<group>.mixins.json), or none. */
    private static List<String> manifestGroups() {
        List<String> out = new ArrayList<>();
        try (InputStream in = EntityClassRegistrations.class.getResourceAsStream("/META-INF/MANIFEST.MF")) {
            if (in == null) return out;
            String configs = new Manifest(in).getMainAttributes().getValue("MixinConfigs");
            if (configs == null) return out;
            for (String c : configs.split(",")) {
                String n = c.trim();
                if (n.startsWith(PREFIX) && n.endsWith(MIXINS) && n.length() > PREFIX.length() + MIXINS.length())
                    out.add(n.substring(PREFIX.length(), n.length() - MIXINS.length()));
            }
        } catch (IOException | RuntimeException e) {
            out.clear();
        }
        return out;
    }

    /** The groups of the mixins our guard table lists (bons.furious.mixin.<group>.<Class>), or none. */
    private static List<String> guardTableGroups() {
        List<String> out = new ArrayList<>();
        try (InputStream in = EntityClassRegistrations.class.getResourceAsStream("/bons_and_furious.guards.tsv")) {
            if (in == null) return out;
            BufferedReader r = new BufferedReader(new InputStreamReader(in, StandardCharsets.UTF_8));
            String line;
            java.util.Set<String> seen = new java.util.TreeSet<>();
            while ((line = r.readLine()) != null) {
                if (!line.startsWith("mixin\tbons.furious.mixin.")) continue;
                int end = line.indexOf('\t', "mixin\t".length());
                if (end < 0) continue;
                String[] parts = line.substring("mixin\t".length(), end).split("\\.");
                if (parts.length >= 5) seen.add(parts[3]);
            }
            out.addAll(seen);
        } catch (IOException | RuntimeException e) {
            out.clear();
        }
        return out;
    }

    private static String resource(String name) throws IOException {
        try (InputStream in = EntityClassRegistrations.class.getResourceAsStream(name)) {
            return in == null ? null : new String(in.readAllBytes(), StandardCharsets.UTF_8);
        }
    }
}
