package bons.furious.patch.mcreator_entity_guards;

import bons.furious.guard.Fingerprint;
import java.util.LinkedHashMap;
import java.util.Map;
import java.util.Set;
import java.util.concurrent.ConcurrentHashMap;
import org.objectweb.asm.tree.ClassNode;
import org.objectweb.asm.tree.MethodNode;
import org.spongepowered.asm.service.MixinService;

/**
 * mcreator_animation_entity_guard (since 1.0.45): one guard per target mod. Guards decides a switch all or nothing (every
 * listed method must match, and a switch that also guards a missing mod is off), which would turn the whole switch off
 * whenever one of its target mods is absent or updated. So the switch's own guard list (patches/mcreator_entity_guards.json
 * "guard") holds only the Forge method every handler relies on, and each mixin is also checked here, before Mixin
 * prepares it (EntityGuardsPlugin.shouldApplyMixin): its target's onEntityTick must match the fingerprint of the tested
 * build (the same Fingerprint.of the guard table uses, read through Mixin's bytecode provider as Guards reads classes).
 * A mod that is not installed is skipped silently; a changed build steps aside alone with one WARN line and its class
 * is left exactly as shipped; every other target keeps the switch.
 *
 * The table is generated from patches/mcreator_entity_guards.json "target_guard" (sha256 by
 * tools/mixedproof/lane_m_target_fill.py, which runs the build's GuardTool fill over those entries) - keep the two equal.
 */
public final class TargetGuards {
    /** One target: our mixin, the mod id that ships the class, the class (internal name), the method and its fingerprint. */
    public record Target(String mixin, String modId, String owner, String method, String desc, String sha256) {}

    static final String DESC = "(Lnet/neoforged/neoforge/event/tick/EntityTickEvent$Pre;)V";
    static final String PKG = "bons.furious.mixin.mcreator_entity_guards.";
    public static final Map<String, Target> BY_MIXIN = new LinkedHashMap<>();
    private static final Set<String> LOGGED = ConcurrentHashMap.newKeySet();

    static {
        // BEGIN TARGETS (generated by tools/mixedproof/lane_m_target_fill.py from patches/mcreator_entity_guards.json)
        add("BornInChaosEntityGuardMixin", "born_in_chaos_v1", "net/mcreator/borninchaosv/init/EntityAnimationFactory", "dd8ab99d4ead6d93fafc823eec1f71623785a904e3d2f9f7ca9f424a52a36d5f");
        add("LuminousBeastsEntityGuardMixin", "luminous_beasts", "net/mcreator/luminousbeasts/init/EntityAnimationFactory", "2d722f556fc02c69d04acbe579ad6d8dc35ee9641b114df6f432d5073059861c");
        // END TARGETS
    }

    private TargetGuards() {
    }

    private static void add(String mixin, String modId, String owner, String sha256) {
        BY_MIXIN.put(PKG + mixin, new Target(PKG + mixin, modId, owner, "onEntityTick", DESC, sha256));
    }

    /** IMixinConfigPlugin.shouldApplyMixin, after the switch's own decision: true when this target is the tested build. */
    public static boolean tested(String mixin, String targetClass) {
        Target t = BY_MIXIN.get(mixin);
        String target = targetClass.replace('/', '.');
        if (t == null) {
            if (LOGGED.add("unknown|" + mixin))
                EntityGuards.LOGGER.warn("Bons and Furious: {}: {} has no recorded target; {} is left unchanged", EntityGuards.KEY, mixin, target);
            return false;
        }
        if (!t.owner().equals(targetClass.replace('.', '/'))) return false;
        Boolean listed = modListed(t.modId());
        if (Boolean.FALSE.equals(listed)) return false;                       // the mod is not installed
        String why = check(t);
        if (why == null) return true;
        if (why.isEmpty()) {
            if (!Boolean.TRUE.equals(listed)) return false;                   // not installed (early mod list unknown)
            why = target + " not found";
        }
        if (LOGGED.add(mixin))
            EntityGuards.LOGGER.warn("Bons and Furious: {} skipped for {} because the installed class does not match the supported version ({}); "
                    + "the class is left unchanged, the other mods' factories keep the switch", EntityGuards.KEY, target, why);
        return false;
    }

    /** null = the tested build; "" = the class is not there (mod not installed); otherwise what differs. */
    static String check(Target t) {
        ClassNode node = read(t.owner());
        if (node == null) return "";
        for (MethodNode m : node.methods) {
            if (m.name.equals(t.method()) && m.desc.equals(t.desc())) {
                String fp = Fingerprint.of(m);
                return fp.equals(t.sha256()) ? null : t.method() + " differs";
            }
        }
        return t.method() + " missing";
    }

    /** Whether FML's early mod list lists the mod; null when that list is not available (offline tools). */
    private static Boolean modListed(String modId) {
        try {
            var mods = net.neoforged.fml.loading.LoadingModList.get();
            return mods == null ? null : mods.getModFileById(modId) != null;
        } catch (Throwable t) {
            return null;
        }
    }

    private static ClassNode read(String internalName) {
        try {
            return MixinService.getService().getBytecodeProvider().getClassNode(internalName.replace('/', '.'));
        } catch (ClassNotFoundException e) {
            return null;
        } catch (Throwable t) {
            EntityGuards.LOGGER.debug("Bons and Furious: {} could not read {}: {}", EntityGuards.KEY, internalName, t.toString());
            return null;
        }
    }
}
